"""Distributor connector interface. RouteNote implements package-and-handoff;
an API distributor (e.g. LabelGrid) can later implement `submit` for real."""
from __future__ import annotations

from abc import ABC, abstractmethod
import re
from datetime import date
from pydantic import BaseModel, Field


VOCAL_WORDS = re.compile(r"\b(vocals?|vocalists?|sing(?:ing|er|ers)?|sung|lyrics?|choir|choirs|rap(?:ping)?|rapper|voices?)\b", re.I)


def check_instrumental(text: str) -> str:
    """MusicGen cannot produce intelligible vocals/lyrics, so describe instruments only."""
    if VOCAL_WORDS.search(text or ""):
        raise ValueError("Vocals/lyrics are not supported: the model cannot sing real lyrics. "
                         "Describe instruments and mood instead; tracks are instrumental.")
    return text


class TrackMetadata(BaseModel):
    title: str = Field(min_length=1, max_length=120)
    track_number: int = Field(default=1, ge=1)
    artist: str = Field(min_length=1, max_length=120)
    explicit: str = Field(default="non-explicit", pattern="^(explicit|non-explicit|cleaned)$")
    instrumental: bool = True
    language: str = "zxx"  # ISO 639; zxx = no linguistic content
    isrc: str | None = Field(default=None, pattern=r"^[A-Z]{2}[A-Z0-9]{3}\d{7}$")
    composer: str | None = None
    lyricist: str | None = None


class ReleaseMetadata(BaseModel):
    title: str = Field(min_length=1, max_length=120)
    release_type: str = Field(default="single", pattern="^(single|ep|album)$")
    primary_artist: str = Field(min_length=1, max_length=120)
    label: str = Field(default="Zi", max_length=120)
    genre: str = "Electronic"
    secondary_genre: str | None = None
    language: str = "No linguistic content (instrumental)"
    release_date: date | None = None  # RouteNote needs >= 14 days ahead for a sales start date
    original_release_date: date | None = None
    upc: str | None = Field(default=None, pattern=r"^\d{12,13}$")
    c_line: str = Field(default="", description="e.g. '2026 Zi'")
    p_line: str = Field(default="", description="e.g. '2026 Zi'")
    explicit: str = Field(default="non-explicit", pattern="^(explicit|non-explicit|cleaned)$")
    ai_generated: bool = True
    ai_disclosure: str = "Audio generated by an AI text-to-music model via Replicate; prompt-directed by the label."
    prompt: str = ""
    tracks: list[TrackMetadata] = Field(min_length=1, max_length=15)


class ValidationReport(BaseModel):
    ok: bool
    errors: list[str] = []
    warnings: list[str] = []


class Distributor(ABC):
    name: str

    @abstractmethod
    def validate(self, meta: ReleaseMetadata) -> ValidationReport: ...

    @abstractmethod
    def build_package(self, release_id: str, meta: ReleaseMetadata, audio_paths: list[str],
                      artwork_path: str, out_dir: str, provenance: dict | None = None) -> str:
        """Return path of a deliverable file/zip."""

    def submit(self, package_path: str):  # optional: only API distributors
        raise NotImplementedError(f"{self.name} has no public upload API; upload manually.")
